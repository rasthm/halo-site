// Builds src/neon-glyphs.ts from the single-stroke EMS Allure script (scripts/fonts/EMSAllure.svg, SIL OFL,
// by Sheldon B. Michaels after Allura by Rob Leuschke; SVG conversion by Windell H. Oskay / Evil Mad Scientist).
// Each glyph is one or more open strokes, which is what lets the site draw words as bent neon tubes.
// Only printable ASCII plus a few typographic marks are kept. Coordinates are rounded to whole font units
// and flipped to SVG's y-down space (baseline at y = 0, ascent negative). Run: node scripts/make-neon.mjs
import fs from 'node:fs';

const src = fs.readFileSync('scripts/fonts/EMSAllure.svg', 'utf8');
const defAdv = +(src.match(/<font[^>]*horiz-adv-x="([\d.]+)"/) || [0, 500])[1];
const ent = (s) =>
  s
    .replace(/&quot;/g, '"')
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&apos;/g, "'")
    .replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)))
    .replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(+d));

const keep = (ch) => (ch >= ' ' && ch <= '~') || '’‘“”–—₹'.includes(ch);

/** Parses an M/L-only path (EMS fonts use straight segments) into polylines, y flipped. */
function polylines(d) {
  const lines = [];
  let cur = null;
  const tok = d.match(/[MLml]|-?\d*\.?\d+(?:e-?\d+)?/g) || [];
  let cmd = 'M';
  for (let i = 0; i < tok.length; ) {
    if (/[MLml]/.test(tok[i])) cmd = tok[i++];
    const x = +tok[i++];
    const y = +tok[i++];
    if (Number.isNaN(x) || Number.isNaN(y)) break;
    const p = [Math.round(x), -Math.round(y)];
    if (cmd === 'M' || cmd === 'm') {
      cur = [p];
      lines.push(cur);
      cmd = 'L';
    } else cur.push(p);
  }
  return lines.filter((l) => l.length > 1);
}

const glyphs = {};
for (const m of src.matchAll(/<glyph([^>]*?)\/?>/g)) {
  const a = m[1];
  const u = a.match(/unicode="([^"]*)"/);
  if (!u) continue;
  const ch = ent(u[1]);
  if ([...ch].length !== 1 || !keep(ch)) continue;
  const adv = Math.round(+((a.match(/horiz-adv-x="([\d.]+)"/) || [0, defAdv])[1]));
  const d = (a.match(/\sd="([^"]*)"/) || [0, ''])[1];
  const lines = polylines(d);
  // Round the corners: a quadratic through each midpoint, so a bent tube has no kinks.
  const mid = (p, q) => [Math.round((p[0] + q[0]) / 2), Math.round((p[1] + q[1]) / 2)];
  const smooth = (l) => {
    if (l.length < 3) return 'M' + l.map((p) => p.join(' ')).join('L');
    let d = 'M' + l[0].join(' ') + 'L' + mid(l[0], l[1]).join(' ');
    for (let i = 1; i < l.length - 1; i++) d += 'Q' + l[i].join(' ') + ' ' + mid(l[i], l[i + 1]).join(' ');
    return d + 'L' + l[l.length - 1].join(' ');
  };
  const path = lines.map(smooth).join('');
  // Ends of the tube with the direction it leaves in (degrees), so an electrode sleeve can sit on it.
  const deg = (p, q) => Math.round((Math.atan2(p[1] - q[1], p[0] - q[0]) * 180) / Math.PI);
  const l0 = lines[0];
  const ln = lines[lines.length - 1];
  const first = l0 ? [...l0[0], deg(l0[0], l0[1])] : null;
  const last = ln ? [...ln[ln.length - 1], deg(ln[ln.length - 1], ln[ln.length - 2])] : null;
  const ys = lines.flat().map((p) => p[1]);
  const box = ys.length ? [Math.min(...ys), Math.max(...ys)] : null;
  glyphs[ch] = [adv, path, first, last, box];
}
// Rupee is not in the font: fall back to "Rs" at layout time.
const out = `// Generated by scripts/make-neon.mjs from EMS Allure (SIL Open Font License). Do not edit by hand.
// [advance, path (y-down, baseline 0), first [x, y, outward angle], last [x, y, outward angle], [top, bottom] of the ink]
export type Glyph = [number, string, [number, number, number] | null, [number, number, number] | null, [number, number] | null];
export const NEON_EM = 1000;
export const NEON_ASCENT = 800;
export const NEON_DESCENT = 200;
export const neonGlyphs: Record<string, Glyph> = ${JSON.stringify(glyphs)};
`;
fs.writeFileSync('src/neon-glyphs.ts', out);
console.log(`neon-glyphs.ts: ${Object.keys(glyphs).length} glyphs, ${(out.length / 1024).toFixed(1)} KB`);
