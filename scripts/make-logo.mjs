// Outlines the Halo wordmark from the brand fonts, so the logo needs no font to render.
// Writes src/logo.ts (paths for the React mark), public/logo.svg and public/favicon.svg.
// Run once after changing the mark: node scripts/make-logo.mjs
import fs from 'node:fs';
import opentype from 'opentype.js';
import wawoff2 from 'wawoff2';

const load = async (file) => {
  const ttf = await wawoff2.decompress(fs.readFileSync(file));
  return opentype.parse(ttf.buffer.slice(ttf.byteOffset, ttf.byteOffset + ttf.byteLength));
};
const archivo = await load('public/fonts/ArchivoBlack-400.woff2');
const inter = await load('public/fonts/Inter-700.woff2');
const r = (n) => Math.round(n * 10) / 10;

// HALO, tracked slightly tight.
const haloSize = 100;
const word = archivo.getPath('HALO', 0, 0, haloSize, {letterSpacing: -0.01});
const wb = word.getBoundingBox();
const wordW = wb.x2 - wb.x1;

// AUTOMATIONS, spaced out to the width of HALO.
const subSize = 15.5;
const letters = 'AUTOMATIONS'.split('');
const adv = letters.map((ch) => inter.charToGlyph(ch).advanceWidth * (subSize / inter.unitsPerEm));
const gap = (wordW - adv.reduce((a, b) => a + b, 0)) / (letters.length - 1);
let x = wb.x1;
const subPaths = [];
for (let i = 0; i < letters.length; i++) {
  subPaths.push(inter.getPath(letters[i], x, 0, subSize).toPathData(1));
  x += adv[i] + gap;
}

// Layout in one coordinate box: ring on top, HALO, AUTOMATIONS.
const pad = 6;
const ringRx = wordW * 0.36;
const ringRy = ringRx * 0.19;
const ringStroke = 8;
const ringCy = pad + ringRy + ringStroke / 2;
const haloTop = ringCy + ringRy + ringStroke / 2 + 10;
const haloBase = haloTop - wb.y1; // wb.y1 is negative (cap height above baseline)
const subBase = haloBase + 12 + subSize * 0.73;
const W = wordW + pad * 2;
const H = subBase + pad;
const dx = pad - wb.x1;

const halo = archivo.getPath('HALO', dx, haloBase, haloSize, {letterSpacing: -0.01}).toPathData(1);
x = pad;
const sub = [];
for (let i = 0; i < letters.length; i++) {
  sub.push(inter.getPath(letters[i], x, subBase, subSize).toPathData(1));
  x += adv[i] + gap;
}
const cx = W / 2;

const ts = `// Generated by scripts/make-logo.mjs from Archivo Black and Inter Bold. Do not edit by hand.
export const logo = {
  width: ${r(W)},
  height: ${r(H)},
  ring: {cx: ${r(cx)}, cy: ${r(ringCy)}, rx: ${r(ringRx)}, ry: ${r(ringRy)}, stroke: ${ringStroke}},
  halo: ${JSON.stringify(halo)},
  sub: ${JSON.stringify(sub.join(''))},
};
`;
fs.writeFileSync('src/logo.ts', ts);

const svg = (fg) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${r(W)} ${r(H)}" role="img" aria-label="Halo Automations">
  <ellipse cx="${r(cx)}" cy="${r(ringCy)}" rx="${r(ringRx)}" ry="${r(ringRy)}" fill="none" stroke="#ff3045" stroke-width="${ringStroke}"/>
  <path fill="${fg}" d="${halo}"/>
  <path fill="${fg}" d="${sub.join('')}"/>
</svg>
`;
fs.writeFileSync('public/logo.svg', svg('#f5f1ef'));
fs.writeFileSync('public/logo-ink.svg', svg('#09090c'));

// Favicon: the ring over a bold H on ink.
const h = archivo.getPath('H', 0, 0, 37);
const hb = h.getBoundingBox();
const hx = 32 - (hb.x2 - hb.x1) / 2 - hb.x1;
const hPath = archivo.getPath('H', hx, 56, 37).toPathData(1);
fs.writeFileSync(
  'public/favicon.svg',
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">
  <rect width="64" height="64" rx="14" fill="#09090c"/>
  <ellipse cx="32" cy="14" rx="18" ry="5" fill="none" stroke="#ff3045" stroke-width="4.2"/>
  <path fill="#f5f1ef" d="${hPath}"/>
</svg>
`,
);
